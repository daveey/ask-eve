#!/usr/bin/env python3
"""scripts/discourse_radar.py — X Discourse Radar & Leak-Checked Reply Queue Builder.

Matches public X posts against Ask Eve's person/topic dossiers (`index/takes.json`) and
audiogram clips (`index/clips.json`), verifies every drafted `@askevepodcast` reply
(`<= 280` chars) through `scripts/leak_check.py`, updates `index/growth.json`, and emits
idempotent D1 SQL upserts into `x_drafts` for David's approval in `/admin/`.

Nothing is ever posted to X by this script; all drafts enter `status='draft'` in D1.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.leak_check import leak_check_draft  # noqa: E402

DEFAULT_GROWTH = ROOT / "index/growth.json"
DEFAULT_CLIPS = ROOT / "index/clips.json"
DEFAULT_TAKES = ROOT / "index/takes.json"
MAX_X_CHARS = 280

PRIORITY_PODCASTER_TARGETS: tuple[str, ...] = (
    "lexfridman",
    "dwarkesh_sp",
    "tylercowen",
    "ezraklein",
    "derekthompson",
    "patrick_oshag",
    "micsolana",
    "ErikTorenberg",
    "benthompson",
    "noahpinion",
    "mattyglesias",
)

PRIORITY_SUBJECT_TARGETS: tuple[str, ...] = (
    "DavidSacks",
    "elonmusk",
    "pmarca",
    "bhorowitz",
    "chamath",
    "Jason",
    "friedberg",
    "theallinpod",
    "peterthiel",
    "bariweiss",
    "ZohranKMamdani",
    "Scott_Wiener",
    "SpeakerPelosi",
    "ConnieChanSF",
    "DarioAmodei",
    "SteveHiltonx",
    "juliewattsTV",
)

PRIORITY_DISCOURSE_TARGETS: tuple[str, ...] = PRIORITY_PODCASTER_TARGETS + PRIORITY_SUBJECT_TARGETS


def build_radar_queries() -> list[str]:
    """Return X search queries combining priority podcasters and show subjects."""
    pod_clause = " OR ".join(f"from:{h}" for h in PRIORITY_PODCASTER_TARGETS)
    sub_clause = " OR ".join(f"from:{h}" for h in PRIORITY_SUBJECT_TARGETS[:10])
    return [
        f"({pod_clause}) (AI OR Anthropic OR SpaceX OR Starshield OR California OR housing OR Thiel OR Musk) -is:retweet",
        f"({sub_clause}) -is:retweet",
    ]


def _sql_str(val: str | None) -> str:
    if val is None:
        return "NULL"
    return "'" + str(val).replace("'", "''") + "'"


def validate_and_enrich_hit(
    hit: dict[str, Any],
    *,
    clips_by_id: dict[str, dict[str, Any]],
    people_slugs: set[str],
) -> dict[str, Any]:
    out = dict(hit)
    tweet_id = str(out.get("tweet_id") or "").strip()
    if not tweet_id.isdigit():
        raise ValueError(f"Invalid tweet_id in radar hit {out.get('id')}: {tweet_id!r}")

    person_slug = str(out.get("person_slug") or "").strip()
    if people_slugs and person_slug not in people_slugs:
        raise ValueError(f"Unknown person_slug {person_slug!r} in radar hit {out.get('id')}")

    clip_id = str(out.get("clip_id") or "").strip()
    if clip_id and clip_id in clips_by_id:
        clip = clips_by_id[clip_id]
        out.setdefault("clip_mp4", f"/assets/clips/{clip_id}.mp4")
        out.setdefault("receipt_url", clip.get("receipt_url", f"https://askevepodcast.com/people/{person_slug}/"))

    reply = str(out.get("draft_reply") or "").strip()
    if not reply:
        raise ValueError(f"Empty draft_reply in radar hit {out.get('id')}")
    if len(reply) > MAX_X_CHARS:
        raise ValueError(f"draft_reply in {out.get('id')} exceeds {MAX_X_CHARS} chars ({len(reply)})")

    check = leak_check_draft("@askevepodcast", f"x_reply:{tweet_id}", reply)
    out["char_count"] = len(reply)
    out["leak_check_passed"] = bool(check["passed"])
    out["leak_check_findings"] = check["findings"]
    out["leak_check_sha256"] = check["sha256"]
    if not check["passed"]:
        raise ValueError(f"Leak check failed for {out.get('id')}: {check['findings']}")
    return out


def render_x_drafts_sql(hits: list[dict[str, Any]]) -> str:
    lines = [
        "-- Generated by scripts/discourse_radar.py; queues leak-checked X replies in x_drafts for /admin/ approval."
    ]
    for h in hits:
        draft_id = h["id"]
        body = h["draft_reply"]
        tweet_id = h["tweet_id"]
        ep_slug = h.get("episode_slug") or "first-encounter"
        passed = 1 if h.get("leak_check_passed") else 0
        findings_json = json.dumps(h.get("leak_check_findings") or [], ensure_ascii=False)
        sha256 = h["leak_check_sha256"]
        created_at = h.get("created_at") or "2026-10-24T04:00:00Z"
        lines.append(
            f"INSERT INTO x_drafts ("
            f"id, body, reply_to_tweet_id, episode_slug, "
            f"leak_check_passed, leak_check_findings_json, leak_check_sha256, "
            f"status, tweet_id, created_at, sent_at, approved_by"
            f") VALUES ("
            f"{_sql_str(draft_id)}, {_sql_str(body)}, {_sql_str(tweet_id)}, {_sql_str(ep_slug)}, "
            f"{passed}, {_sql_str(findings_json)}, {_sql_str(sha256)}, "
            f"'draft', NULL, {_sql_str(created_at)}, NULL, NULL"
            f") ON CONFLICT(id) DO UPDATE SET "
            f"body=excluded.body, reply_to_tweet_id=excluded.reply_to_tweet_id, "
            f"episode_slug=excluded.episode_slug, leak_check_passed=excluded.leak_check_passed, "
            f"leak_check_findings_json=excluded.leak_check_findings_json, "
            f"leak_check_sha256=excluded.leak_check_sha256;"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--growth", type=Path, default=DEFAULT_GROWTH, help="Path to index/growth.json")
    ap.add_argument("--clips", type=Path, default=DEFAULT_CLIPS, help="Path to index/clips.json")
    ap.add_argument("--takes", type=Path, default=DEFAULT_TAKES, help="Path to index/takes.json")
    ap.add_argument("--input", type=Path, default=None, help="Optional JSON file of radar hits to merge")
    ap.add_argument("--sql-out", type=Path, default=None, help="Optional path to write D1 x_drafts upsert SQL")
    args = ap.parse_args(argv)

    growth = json.loads(args.growth.read_text())
    clips_doc = json.loads(args.clips.read_text()) if args.clips.exists() else {"clips": []}
    takes_doc = json.loads(args.takes.read_text()) if args.takes.exists() else {"people": {}}

    clips_by_id = {c["id"]: c for c in clips_doc.get("clips", [])}
    people_slugs = set((takes_doc.get("people") or {}).keys())

    hits = growth.get("radar_hits", [])
    if args.input:
        incoming = json.loads(args.input.read_text())
        if isinstance(incoming, dict):
            incoming = incoming.get("radar_hits", [])
        by_id = {h["id"]: h for h in hits}
        for item in incoming:
            by_id[item["id"]] = item
        hits = list(by_id.values())

    validated = [
        validate_and_enrich_hit(h, clips_by_id=clips_by_id, people_slugs=people_slugs)
        for h in hits
    ]
    growth["radar_hits"] = validated
    args.growth.write_text(json.dumps(growth, indent=2, ensure_ascii=False) + "\n")

    sql = render_x_drafts_sql(validated)
    if args.sql_out:
        args.sql_out.write_text(sql)

    print(
        json.dumps(
            {
                "validated_hits": len(validated),
                "all_leak_check_passed": all(h["leak_check_passed"] for h in validated),
                "max_chars": max((h["char_count"] for h in validated), default=0),
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
