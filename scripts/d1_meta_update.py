#!/usr/bin/env python3
"""Metadata-only D1 update for an already published episode: no audio, chapters or people are touched.

Syncs the episode row's public slug (index/slugs.json rename; the row id stays), title, episode_type (+ episode_number: NULL for bonus) and summary (= the front-matter `context` note) and source_url (front-matter `source`; NULL when removed) and transcript_sha256 / transcript_bytes
(so build_site.py's sha check passes after a front-matter edit), and chapter *titles* from artifacts/<stem>/chapters.json
(matched on start time; no chapter is added, moved or deleted). guid, audio_* and published_at are never
changed, so podcast apps keep treating it as the same episode. Used by .github/workflows/meta.yml:

    python3 scripts/d1_meta_update.py episodes/<date>_<slug>.md > meta.sql
    wrangler d1 execute ask-eve-meta --remote --file meta.sql
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

# stdlib only (runs on a bare Actions runner): same parsing/quoting as d1_upsert.py, without its rapidfuzz import.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from frontmatter import episode_number, episode_type, parse_front_matter_block, public_slug  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def q(v) -> str:
    return "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"



def front_matter(md: str) -> dict:
    m = re.match(r"^---\n(.*?)\n---\n", md, re.S)
    if not m:
        raise SystemExit("transcript has no front matter")
    return parse_front_matter_block(m.group(1))


def build_sql(transcript: Path, repo_root: Path = ROOT) -> str:
    data = transcript.read_bytes()
    fm = front_matter(data.decode("utf-8"))
    title = fm.get("title", "").strip()
    if not title:
        raise SystemExit(f"{transcript}: front matter has no title")
    rel = transcript.resolve().relative_to(repo_root.resolve()).as_posix()
    old, slug = transcript.stem.split("_", 1)[1], public_slug(transcript.stem)   # index/slugs.json rename
    ctx = fm.get("context") or fm.get("summary")
    summary = f"summary={q(ctx)}, " if isinstance(ctx, str) and ctx else ""
    etype = episode_type(fm)
    # bonus: no number (feed omits <itunes:episode>); full: the front-matter number when given, else unchanged
    num = "episode_number=NULL, " if etype == "bonus" else (
        f"episode_number={episode_number(fm)}, " if episode_number(fm) is not None else "")
    return (f"-- generated by scripts/d1_meta_update.py (metadata only)\n"
            f"UPDATE episodes SET slug={q(slug)}, title={q(title)}, {summary}episode_type={q(etype)}, {num}source_url={q(fm.get('source') or None)}, transcript_sha256={q(hashlib.sha256(data).hexdigest())}, "
            f"transcript_bytes={len(data)}, updated_at=strftime('%Y-%m-%dT%H:%M:%SZ','now') "
            f"WHERE slug IN ({q(old)}, {q(slug)}) AND transcript_path={q(rel)};\n"
            + chapter_titles_sql(repo_root / "artifacts" / transcript.stem / "chapters.json", slug) +
            f"SELECT slug, guid, title, episode_type, episode_number, summary, transcript_sha256, transcript_bytes, audio_url FROM episodes WHERE slug={q(slug)};\n")


def chapter_titles_sql(chapters_json: Path, slug: str) -> str:
    """UPDATE the title of each existing English chapter whose start time matches artifacts/<stem>/chapters.json."""
    if not chapters_json.is_file():
        return ""
    out = []
    for c in json.loads(chapters_json.read_text()).get("chapters", []):
        out.append(f"UPDATE chapters SET title={q(c['title'])} WHERE episode_id=(SELECT id FROM episodes WHERE slug={q(slug)}) "
                   f"AND language='en' AND abs(start_seconds - {float(c['startTime'])}) < 0.005;\n")
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("transcript", type=Path, help="episodes/<date>_<slug>.md")
    a = ap.parse_args(argv)
    sys.stdout.write(build_sql(a.transcript))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
